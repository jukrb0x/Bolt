/** Describe a resolved plugin/local action using the plugin's describe() if available. */
function describeUses(
  ref: string,
  params: Record<string, string>,
  registry: PluginRegistry,
): string {
  // Plugin call: "namespace/handler"
  const slash = ref.indexOf("/");
  if (slash === -1) return ref;

  const ns = ref.slice(0, slash);
  const handler = ref.slice(slash + 1);
  const plugin = registry.get(ns);
  if (!plugin) return ref;

  if (plugin.describe) {
    const desc = plugin.describe(handler, params);
    if (desc) return desc;
  }

  const paramMap = getParamMap(plugin as any, handler);
  if (paramMap && paramMap.size > 0) {
    const paramDescs = [...paramMap.entries()].map(
      ([name, meta]) => `${name}: ${meta.description}`,
    );
    return `${ref} (${paramDescs.join(", ")})`;
  }

  return ref;
}

function describePlanNodes(nodes: PlanNode[], registry: PluginRegistry): string {
  return nodes
    .map((node) => {
      if (node.kind === "run") return node.command;
      if (node.kind === "uses") return describeUses(node.ref, node.params, registry);
      return describePlanNodes(node.nodes, registry) || `call:${node.name}`;
    })
    .join(" → ");
}

function describeInvalidPlan(messages: string[]): string {
  for (const message of messages) {
    if (message.startsWith("Task call cycle: ")) {
      const name = message.slice("Task call cycle: ".length).split(" -> ").at(-1);
      return `call:${name ?? "?"} (cycle)`;
    }
    const unknown = message.match(/^Unknown task: "(.+)"$/);
    if (unknown) return `call:${unknown[1]}`;
  }
  return messages.join("; ");
}

/** Describe a task from the same effective plan used for execution and inspection. */
function describeTask(
  name: string,
  cfg: BoltConfig,
  registry: PluginRegistry,
  params: Record<string, string>,
): string {
  const result = resolveRunPlan(cfg, { kind: "tasks", names: [name], params });
  if (!result.ok) return describeInvalidPlan(result.errors.map((error) => error.message));
  return describePlanNodes(result.plan.tasks[0]?.nodes ?? [], registry);
}

export function generateAiContext(
  cfg: BoltConfig,
  configPath: string,
  registry: PluginRegistry,
  params: Record<string, string> = {},
): string {
  const yamlRaw = readFileSync(configPath, "utf8");
  const catalog = pluginCatalog(registry);
  // bolt.yaml text plus the sorted catalog actually written. Not bolt.local.yaml, sources, or node_modules.
  const hash = createHash("sha256")
    .update(yamlRaw)
    .update("\0")
    .update(stableCatalogJson(catalog))
    .digest("hex")
    .slice(0, 16);

  const lines: string[] = [];

  lines.push(`<!-- generated by bolt ai — do not edit manually -->`);
  lines.push(`<!-- context hash: ${hash} -->`);
  lines.push(`<!-- inputs: bolt.yaml, plugin manifests -->`);
  lines.push(`<!-- manifest format: ${MANIFEST_FORMAT} -->`);
  lines.push(`<!-- config: ${configPath} -->`);
  lines.push(``);
  lines.push(`# Bolt — ${cfg.project.name}`);
  lines.push(``);
  lines.push(`Bolt is a CLI tool for Unreal Engine workflow automation.`);
  lines.push(`Run commands from the directory containing bolt.yaml (or any child directory).`);
  lines.push(``);
  lines.push(`Model: a **task** is a named list of steps; a **flow** is an ordered set of`);
  lines.push(`tasks with a fail policy. \`bolt run <task...>\` runs tasks in the order given;`);
  lines.push(`\`bolt run <flow>\` runs a predefined flow.`);
  lines.push(
    `Step keys: \`uses\`: plugin/local action; \`call\`: reusable task; \`run\`: shell command.`,
  );
  lines.push(``);

  // --- Quick reference table ---
  lines.push(`## Quick Reference`);
  lines.push(``);
  lines.push(`| Name | Command | Steps |`);
  lines.push(`|------|---------|-------|`);

  for (const name of Object.keys(cfg.tasks)) {
    lines.push(`| ${name} | \`bolt run ${name}\` | ${describeTask(name, cfg, registry, params)} |`);
  }
  for (const [name, flow] of Object.entries(cfg.flows)) {
    lines.push(`| ${name} (flow) | \`bolt run ${name}\` | ${flow.steps.join(" → ")} |`);
  }
  lines.push(``);

  // --- Tasks detail ---
  lines.push(`## Tasks (\`bolt run <task...>\`)`);
  lines.push(``);
  lines.push(
    `Named step sequences. Chain multiple in typed order: \`bolt run update build start\`.`,
  );
  lines.push(
    `Pass params with \`--key=value\` (applies to the whole run, e.g. \`--target=client\`).`,
  );
  lines.push(``);

  for (const name of Object.keys(cfg.tasks)) {
    lines.push(
      `- **${name}** — \`bolt run ${name}\` — ${describeTask(name, cfg, registry, params)}`,
    );
  }
  lines.push(``);

  // --- Flows detail ---
  if (Object.keys(cfg.flows).length > 0) {
    lines.push(`## Flows (\`bolt run <flow>\`)`);
    lines.push(``);
    lines.push(`Ordered task compositions. Fail-fast: the first failing task aborts the flow,`);
    lines.push(`unless it is listed in \`continue_on_fail\`.`);
    lines.push(``);

    for (const [name, flow] of Object.entries(cfg.flows)) {
      const cont = flow.continue_on_fail.length
        ? ` (continue_on_fail: ${flow.continue_on_fail.join(", ")})`
        : "";
      const desc = flow.description ? `${flow.description} — ` : "";
      lines.push(`- **${name}**${cont}: ${desc}${flow.steps.join(" → ")}`);
    }
    lines.push(``);
  }

  lines.push(...renderPlugins(catalog));

  // --- Targets (ue plugin; config is already canonical) ---
  const targets = resolveUeTargets(cfg.plugins);
  if (Object.keys(targets).length > 0) {
    lines.push(`## Targets`);
    lines.push(``);
    for (const [name, t] of Object.entries(targets)) {
      const detail = t.name ? `${t.kind} · ${t.name} · ${t.config}` : `${t.kind} · ${t.config}`;
      lines.push(`- **${name}**: ${detail}`);
    }
    lines.push(``);
  }

  // --- Flags ---
  lines.push(`## Flags`);
  lines.push(``);
  lines.push(
    `- \`--dry-run\` — skips \`run:\` steps and local actions, but still calls plugin handlers in the current version. Use \`bolt inspect\` first to show the plan, and get the user's consent before running \`--dry-run\`.`,
  );
  lines.push(
    `- \`--key=value\` — pass parameters to the run (e.g. \`--target=client --config=debug\`)`,
  );
  lines.push(`- \`--config=debuggame\` (aliases: \`dbggame\`, \`DebugGame\`) — Unreal DebugGame`);
  lines.push(``);

  lines.push(`## Notifications`);
  lines.push(``);
  lines.push(
    `Start notifications show the top-level task list and recursively owned actions once per invocation.`,
  );
  lines.push(``);

  // --- Introspection ---
  lines.push(`## Introspection`);
  lines.push(``);
  lines.push(`- \`bolt list\` — list all tasks and flows`);
  lines.push(`- \`bolt inspect <name...>\` — show resolved steps for a task or flow`);
  lines.push(`- \`bolt info\` — project and VCS summary`);
  lines.push(`- \`bolt check\` — validate bolt.yaml schema`);
  lines.push(``);

  return lines.join("\n");
}

type AiMode = false | true | "confirm";

interface CatalogParam {
  name: string;
  description?: string;
  type?: string;
  required?: boolean;
  enum?: string[];
  default?: unknown;
}

interface CatalogHandler {
  name: string;
  description?: string;
  ai?: AiMode;
  params: CatalogParam[];
  capabilities?: string[];
}

interface CatalogPlugin {
  namespace: string;
  description?: string;
  handlers: CatalogHandler[];
}

const CONFIRM_SENTENCE = "This step has side effects and the user must run `bolt run` themselves.";

function cmp(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function clean(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  const text = value.trim();
  return text ? text : undefined;
}

function pluginCatalog(registry: PluginRegistry): CatalogPlugin[] {
  const plugins: CatalogPlugin[] = [];
  for (const namespace of registry.listNamespaces()) {
    const plugin = registry.get(namespace);
    if (!plugin) continue;
    const entry = catalogPlugin(plugin);
    if (entry.handlers.length > 0) plugins.push(entry);
  }
  plugins.sort((a, b) => cmp(a.namespace, b.namespace));
  return plugins;
}

function catalogPlugin(plugin: BoltPlugin): CatalogPlugin {
  const manifest = readManifest(plugin);
  const source = manifest?.handlers ?? plugin.handlers;
  const description = clean(manifest?.description);
  return {
    namespace: plugin.namespace,
    ...(description ? { description } : {}),
    handlers: listedHandlers(plugin, source),
  };
}

function readManifest(
  plugin: BoltPlugin,
): { description?: string; handlers?: Record<string, unknown> } | undefined {
  const candidate = (plugin as { manifest?: unknown }).manifest;
  if (!candidate || typeof candidate !== "object") return undefined;
  const manifest = candidate as { description?: unknown; handlers?: unknown };
  const handlers =
    manifest.handlers && typeof manifest.handlers === "object" && !Array.isArray(manifest.handlers)
      ? (manifest.handlers as Record<string, unknown>)
      : undefined;
  return { description: clean(manifest.description), handlers };
}

function listedHandlers(plugin: BoltPlugin, handlers: object): CatalogHandler[] {
  const entries = handlers as Record<string, unknown>;
  const listed: CatalogHandler[] = [];
  for (const name of Object.keys(entries).sort(cmp)) {
    const meta = asRecord(entries[name]);
    const ai = normalizeAi(meta?.ai);
    if (ai === false) continue;
    listed.push(catalogHandler(plugin, name, ai, meta));
  }
  return listed;
}

function catalogHandler(
  plugin: BoltPlugin,
  name: string,
  ai: AiMode | undefined,
  meta: Record<string, unknown> | undefined,
): CatalogHandler {
  const description = clean(meta?.description) ?? describeHandler(plugin, name);
  const capabilities = Array.isArray(meta?.capabilities)
    ? (meta.capabilities as unknown[]).filter((tag): tag is string => typeof tag === "string")
    : [];
  return {
    name,
    ...(description ? { description } : {}),
    ...(ai ? { ai } : {}),
    params: paramsFor(meta, plugin, name),
    ...(capabilities.length > 0 ? { capabilities } : {}),
  };
}

function describeHandler(plugin: BoltPlugin, name: string): string | undefined {
  return clean(plugin.describe?.(name, {}));
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  if (value === null || (typeof value !== "object" && typeof value !== "function"))
    return undefined;
  return value as Record<string, unknown>;
}

function normalizeAi(ai: unknown): AiMode | undefined {
  if (ai === false || ai === true || ai === "confirm") return ai;
  return undefined;
}

function paramsFor(
  meta: Record<string, unknown> | undefined,
  plugin: BoltPlugin,
  name: string,
): CatalogParam[] {
  return (
    paramsFromSchema(meta?.paramsSchema) ??
    paramsFromSchema(meta?.params) ??
    paramsFromMap(plugin, name)
  );
}

function paramsFromSchema(schema: unknown): CatalogParam[] | undefined {
  const record = asRecord(schema);
  if (!record || !record.properties || typeof record.properties !== "object") return undefined;
  if (Array.isArray(record.properties)) return undefined;
  const required = new Set(
    Array.isArray(record.required)
      ? record.required.filter((name): name is string => typeof name === "string")
      : [],
  );
  const properties = record.properties as Record<string, unknown>;
  return Object.keys(properties)
    .sort(cmp)
    .map((name) => paramFromProperty(name, properties[name], required.has(name)));
}

function paramFromProperty(name: string, property: unknown, required: boolean): CatalogParam {
  const prop = asRecord(property) ?? {};
  const param: CatalogParam = { name };
  if (typeof prop.type === "string") param.type = prop.type;
  const description = clean(prop.description);
  if (description) param.description = description;
  if (Array.isArray(prop.enum)) {
    const values = prop.enum.filter(
      (item) => typeof item === "string" || typeof item === "number" || typeof item === "boolean",
    );
    if (values.length > 0) param.enum = values.map(String);
  }
  if ("default" in prop && prop.default !== undefined) param.default = prop.default;
  if (required) param.required = true;
  return param;
}

function paramsFromMap(plugin: BoltPlugin, name: string): CatalogParam[] {
  const map = getParamMap(plugin as { constructor: any }, name);
  if (!map) return [];
  return [...map.entries()]
    .map(([paramName, meta]) => ({ name: paramName, description: meta.description }))
    .sort((a, b) => cmp(a.name, b.name));
}

function formatParam(param: CatalogParam): string {
  const details: string[] = [];
  if (param.type) details.push(param.type);
  if (param.required) details.push("required");
  if (param.enum?.length) details.push(`enum: ${param.enum.join(" | ")}`);
  if (param.default !== undefined) details.push(`default ${formatDefault(param.default)}`);
  const meta = details.length ? ` (${details.join(", ")})` : "";
  const desc = param.description ? `: ${param.description}` : "";
  return `\`${param.name}\`${meta}${desc}`;
}

function formatDefault(value: unknown): string {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return JSON.stringify(value);
}

function renderPlugins(catalog: CatalogPlugin[]): string[] {
  if (catalog.length === 0) return [];
  const lines = ["## Plugins", ""];
  for (const plugin of catalog) {
    lines.push(`### \`${plugin.namespace}\``);
    lines.push("");
    if (plugin.description) {
      lines.push(plugin.description);
      lines.push("");
    }
    for (const handler of plugin.handlers) {
      const desc = handler.description ? ` — ${handler.description}` : "";
      lines.push(`- **${handler.name}**${desc}`);
      for (const param of handler.params) lines.push(`  - ${formatParam(param)}`);
      if (handler.capabilities) lines.push(`  - capabilities: ${handler.capabilities.join(", ")}`);
      if (handler.ai === "confirm") lines.push(`  - ${CONFIRM_SENTENCE}`);
    }
    lines.push("");
  }
  return lines;
}

function stableCatalogJson(catalog: CatalogPlugin[]): string {
  return JSON.stringify(
    catalog.map((plugin) => {
      const entry: Record<string, unknown> = { namespace: plugin.namespace };
      if (plugin.description) entry.description = plugin.description;
      entry.handlers = plugin.handlers.map((handler) => {
        const row: Record<string, unknown> = { name: handler.name };
        if (handler.description) row.description = handler.description;
        if (handler.ai === "confirm") row.confirm = true;
        if (handler.capabilities) row.capabilities = handler.capabilities;
        row.params = handler.params.map((param) => {
          const item: Record<string, unknown> = { name: param.name };
          if (param.description) item.description = param.description;
          if (param.type) item.type = param.type;
          if (param.required) item.required = true;
          if (param.enum) item.enum = param.enum;
          if (param.default !== undefined) item.default = param.default;
          return item;
        });
        return row;
      });
      return entry;
    }),
  );
}

/**
 * Warning text when `.bolt/ai-context.md` was written by a bolt with another
 * manifest format, or undefined when it is current or absent.
 */
export function staleAiContextWarning(configDir: string): string | undefined {
  const file = path.join(configDir, ".bolt", "ai-context.md");
  if (!existsSync(file)) return undefined;
  const head = readFileSync(file, "utf8").slice(0, 2000);
  const found = /<!-- manifest format: (\d+) -->/.exec(head)?.[1] ?? "1";
  if (found === String(MANIFEST_FORMAT)) return undefined;
  return `AI_CONTEXT_STALE: .bolt/ai-context.md was generated by an older bolt (manifest format m${found}, need m${MANIFEST_FORMAT}); plugin capabilities and AI permissions in it are out of date. Run: bolt ai`;
}
